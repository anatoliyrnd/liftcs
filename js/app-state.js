/**
 * Глобальное состояние приложения, разделяемое между контроллерами.
 * Живёт в памяти, сбрасывается при F5.
 *
 * Используется для передачи контекста между страницами, когда hash-роутер
 * не может протащить данные сам.
 */
export const appState = {
    /**
     * Контекст для формы создания новой заявки.
     * Заполняется после закрытия заявки с галочкой «создать новую для того же объекта».
     *
     * Формат:
     *   {
     *     from_ticket_id: number | null,   // ID закрытой заявки (для подписи)
     *     address: string,                  // готовый адрес
     *     city_id, street_id, home_id, object_id
     *   }
     * Очищается сразу после применения в CreateController.mount.
     */
    pendingCreateAddress: null,

    /** Сбросить весь стейт (например, при логауте). */
    reset() {
        this.pendingCreateAddress = null;
    }
};